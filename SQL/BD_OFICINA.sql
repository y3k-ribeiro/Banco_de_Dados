/* QUANTOS CARROS CADA CLIENTE TEM? */
SELECT
    CLIENTES.NOME,
    COUNT(VEICULOS.ID) AS "QUANTIDADE DE CARROS"
FROM CLIENTES
LEFT JOIN VEICULOS
    ON CLIENTES.ID = VEICULOS.FK_CLIENTES_ID
GROUP BY CLIENTES.ID, CLIENTES.NOME;


/* QUANTOS AGENDAMENTOS CADA VEÍCULO TEM? */
SELECT
    VEICULOS.MODELO,
    COUNT(AGENDAMENTOS.ID) AS "QUANTIDADE DE AGENDAMENTOS"
FROM VEICULOS
LEFT JOIN AGENDAMENTOS
    ON VEICULOS.ID = AGENDAMENTOS.FK_VEICULOS_ID
GROUP BY VEICULOS.ID, VEICULOS.MODELO;


/* QUANTOS AGENDAMENTOS CADA CLIENTE TEM? */
SELECT
    CLIENTES.NOME,
    COUNT(AGENDAMENTOS.ID) AS "TOTAL DE AGENDAMENTOS"
FROM CLIENTES
LEFT JOIN VEICULOS
    ON CLIENTES.ID = VEICULOS.FK_CLIENTES_ID
LEFT JOIN AGENDAMENTOS
    ON VEICULOS.ID = AGENDAMENTOS.FK_VEICULOS_ID
GROUP BY CLIENTES.ID, CLIENTES.NOME;
