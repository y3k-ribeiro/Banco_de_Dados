CREATE DATABASE IF NOT EXISTS BD_OFICINA;
USE BD_OFICINA;

CREATE TABLE IF NOT EXISTS CLIENTES(
	ID INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    CPF VARCHAR(255) NOT NULL,
    TELEFONE VARCHAR(20),
    EMAIL VARCHAR(100),
    CREATE_AT TIMESTAMP,
    UPDATE_AT TIMESTAMP
);

CREATE TABLE IF NOT EXISTS VEICULOS(
	ID INT PRIMARY KEY AUTO_INCREMENT,
    PLACA VARCHAR(100) NOT NULL,
    MARCA VARCHAR(50) NOT NULL,
    MODELO VARCHAR(50),
    FK_CLIENTES_ID INT,
    FOREIGN KEY (FK_CLIENTES_ID) REFERENCES CLIENTES(ID),
    CREATE_AT TIMESTAMP,
    UPDATE_AT TIMESTAMP
);

CREATE TABLE IF NOT EXISTS AGENDAMENTOS(
	ID INT PRIMARY KEY AUTO_INCREMENT,
    DATA DATE NOT NULL,
    HORA TIME NOT NULL,
    DESCRICAO VARCHAR(255),
    FK_VEICULOS_ID INT,
    FOREIGN KEY (FK_VEICULOS_ID) REFERENCES VEICULOS(ID),
    CREATE_AT TIMESTAMP,
    UPDATE_AT TIMESTAMP 
);

