SELECT
    CLIENTES.NOME AS CLIENTE,
    COUNT(DISTINCT VEICULOS.ID) AS QUANTIDADE_CARROS,
    GROUP_CONCAT(DISTINCT VEICULOS.MODELO SEPARATOR ', ') AS VEICULOS,
    COUNT(DISTINCT AGENDAMENTOS.ID) AS QUANTIDADE_AGENDAMENTOS

FROM CLIENTES

LEFT JOIN VEICULOS
ON CLIENTES.ID = VEICULOS.FK_CLIENTES_ID

LEFT JOIN AGENDAMENTOS
ON VEICULOS.ID = AGENDAMENTOS.FK_VEICULOS_ID

GROUP BY CLIENTES.ID, CLIENTES.NOME;

